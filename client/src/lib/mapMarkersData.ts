const byId = new Map(mapMarkers.map((marker) => [marker.id, marker]));

export function markerById(id: string) {
  const marker = byId.get(id);
  if (!marker) throw new Error(`未知地點：${id}`);
  return marker;
}

export function markersForDays(days: number[]) {
  const wanted = new Set(days);
  return mapMarkers.filter((marker) => marker.days.some((day) => wanted.has(day)));
}
